def test_daily_estimate_is_min_of_both_directions() -> None:
    """Z_d = min(Σ gen to community, Σ cons from community), share per side."""

    data = week()
    zero = estimate({"beg": [data]}, lambda day: True)
    sums = day_sums(data)
    for (direction, day), total in sums.items():
        z = min(sums[G, day], sums[C, day])
        assert zero.shares[("beg", direction, day)] == pytest.approx(z / total)
    month = (2026, 6)
    expected = math.fsum(min(sums[G, d], sums[C, d]) for d in {d for _, d in sums})
    assert zero.month_kwh["beg", month] == pytest.approx(expected)
    # No plan on these days: nothing estimated.
    assert estimate({"beg": [data]}, lambda day: False).shares == {}


def _settled_for(data: AnalysisData, rate: float) -> tuple[float, float, Any]:
    """Invoice amounts that a true Zero rate ``rate`` would give."""

    zero = estimate({"beg": [data]}, lambda day: True)
    kwh = zero.month_kwh["beg", (2026, 6)]
    totals = {}
    for direction in Direction:
        non_zero = math.fsum(
            p.money * (1 - zero.shares[("beg", direction, local_date(p.start))])
            for p in data.points(direction)
            if p.money is not None
        )
        totals[direction] = round(non_zero + kwh * rate, 2)
    return totals[G], totals[C], zero


def test_rate_derived_from_settled_month() -> None:
    """The derived rate reproduces the invoice; the settled month needs no scaling."""

    data = week()
    feed_in, cost, zero = _settled_for(data, 0.03)
    settlements = build_settlements(
        rows(
            tx("2026-07-20", feed_in, "Einspeisevergütung Juni 2026", "Example BEG"),
            tx("2026-07-20", -cost, "Strombezug Juni 2026", "Example BEG"),
        ),
        NAMES,
    )
    derived = derive_rates({"beg": [data]}, zero, settlements)
    kwh = zero.month_kwh["beg", (2026, 6)]
    for direction in Direction:
        assert derived["beg", direction, (2026, 6)] == pytest.approx(
            0.03, abs=0.01 / kwh
        )
    latest = latest_rates({}, derived)
    repriced = reprice({"beg": [data]}, zero, rate_lookup(derived, latest))["beg"][0]
    total = math.fsum(p.money for p in repriced.consumption if p.money is not None)
    assert total == pytest.approx(cost, abs=1e-6)
    # kWh untouched.
    assert [p.community for p in repriced.consumption] == [
        p.community for p in data.consumption
    ]


def test_reprice_unsettled_with_latest_rate() -> None:
    """An unsettled month uses the latest rate; the formula per hour."""

    data = week()
    zero = estimate({"beg": [data]}, lambda day: True)
    latest = {("beg", C): ZeroRate((2026, 5), 0.02)}
    repriced = reprice({"beg": [data]}, zero, rate_lookup({}, latest))["beg"][0]
    for before, after in zip(data.consumption, repriced.consumption, strict=True):
        if before.money is None or before.community is None:
            assert after == before
            continue
        r = zero.shares["beg", C, local_date(before.start)]
        assert after.money == pytest.approx(
            before.money * (1 - r) + before.community * r * 0.02
        )
    # No rate for generation yet: unchanged.
    assert repriced.generation == data.generation


def test_no_rate_without_enough_zero_or_when_negative() -> None:
    """Under MIN_ZERO_KWH, or a negative result: no rate."""

    data = week()
    zero = estimate({"beg": [data]}, lambda day: True)
    small = type(zero)(zero.shares, dict.fromkeys(zero.month_kwh, MIN_ZERO_KWH / 2))
    settlements = build_settlements(
        rows(tx("2026-07-20", -0.01, "Strombezug Juni 2026", "Example BEG")),
        NAMES,
    )
    assert derive_rates({"beg": [data]}, small, settlements) == {}
    # A tiny invoice with lots of Zero would need a negative rate.
    assert derive_rates({"beg": [data]}, zero, settlements) == {}


def test_latest_rate_and_store_round_trip() -> None:
    """The latest settled month wins; broken stored entries are skipped."""

    stored = {("beg", C): ZeroRate((2026, 3), 0.024)}
    newer = latest_rates(stored, {("beg", C, (2026, 5)): 0.025})
    assert newer["beg", C] == ZeroRate((2026, 5), 0.025)
    older = latest_rates(stored, {("beg", C, (2026, 1)): 0.03})
    assert older["beg", C] == ZeroRate((2026, 3), 0.024)
    raw = rates_to_store(newer)
    assert raw == {"beg/Consumption": {"month": "2026-05", "rate": 0.025}}
    assert rates_from_store(raw) == newer
    assert rates_from_store({"x": 1, "beg/Nope": {"month": "2026-01", "rate": 1}}) == {}
    assert rates_from_store(None) == {}


def test_export_keeps_plan_numbers_recognisable() -> None:
    """Plan numbers get the same synthetic numbers as the metering points."""

    out = redact_export(own_site_mp_raw(), Pseudonyms(), [])
    points = out[0]["memberMeteringpoints"]
    numbers = {mp["consumptionOrGeneration"]: mp["number"] for mp in points}
    gen = next(mp for mp in points if mp["consumptionOrGeneration"] == "Generation")
    plan = gen["sendingZeroPlans"][0]
    assert plan["fromMeteringpointNumber"] == numbers["Generation"]
    assert plan["toMeteringpointNumber"] == numbers["Consumption"]
    assert GEN_NUMBER not in str(out) or numbers["Generation"] == GEN_NUMBER


