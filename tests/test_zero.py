C, G = Direction.CONSUMPTION, Direction.GENERATION
CONS_NUMBER = "AT0000000000000000000000000001001"
GEN_NUMBER = "AT0000000000000000000000000001002"


def own_site_mp_raw() -> Any:
    """Return the metering-point fixture with an own-site Zero plan."""

    raw = copy.deepcopy(load_fixture("metering_point_single.json"))
    plan = {
        "id": 8001,
        "fromName": "Example sender",
        "toName": "Example receiver",
        "fromMeteringpointNumber": GEN_NUMBER,
        "toMeteringpointNumber": CONS_NUMBER,
        "begin": "2026-02-01",
        "end": None,
        "status": "Active",
        "isAutoGenerated": False,
    }
    for mp in raw[0]["memberMeteringpoints"]:
        if mp["consumptionOrGeneration"] == "Consumption":
            mp["receivingZeroPlans"] = [plan]
            mp["sendingZeroPlans"] = []
        else:
            mp["sendingZeroPlans"] = [plan]
            mp["receivingZeroPlans"] = []
    return raw


def week() -> AnalysisData:
    return parse_analysis(load_fixture("analysis_hour_normal_beg.json"))


def day_sums(data: AnalysisData) -> dict[tuple[Direction, date], float]:
    out: dict[tuple[Direction, date], float] = defaultdict(float)
    for direction in Direction:
        for p in data.points(direction):
            if p.community is not None:
                out[direction, local_date(p.start)] += p.community
    return out


