async def test_run_with_zero_plan_and_settlement(hass: Any, env: Any) -> None:
    """Rates derived and stored; a settled month with its own rate isn't rescaled."""

    coordinator, _, client = make(hass, options={"daily_window_days": 7})
    client.mp_raw = own_site_mp_raw()
    client.transactions_raw = [
        tx("2026-06-08", -0.50, "Strombezug Juni 2026", "Example BEG"),
        tx("2026-06-08", 1.20, "Einspeisevergütung Juni 2026", "Example BEG"),
    ]
    summary = await coordinator.async_run(RunRequest(RunType.DAILY))
    assert summary is not None
    assert summary.status is RunStatus.OK
    assert summary.settlement is not None
    assert "beg/2026-06" in summary.settlement["zero_months"]
    rates = summary.settlement["zero_rates"]
    months = summary.settlement["months"]
    for direction in ("Consumption", "Generation"):
        key = f"beg/{direction}"
        if key in rates:
            # Repriced with its own rate, the month already equals the invoice.
            assert months[f"beg/{direction}/2026-06"]["factor"] == pytest.approx(
                1.0, abs=1e-3
            )
    assert coordinator.state.zero_rates == rates
