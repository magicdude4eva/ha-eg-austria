def test_own_site_plan_found_other_plans_ignored() -> None:
    """Only a plan between two selected points counts."""

    own = parse_metering_points(own_site_mp_raw())
    site = site_info(own, "5001", [1001, 1002], [2001, 2002])
    assert site.zero_ranges == ((date(2026, 2, 1), None),)
    assert site.own_zero_on(date(2026, 6, 3))
    assert not site.own_zero_on(date(2026, 1, 31))
    # The plain fixture's plans go to another site: no estimate.
    other = parse_metering_points(load_fixture("metering_point_single.json"))
    assert site_info(other, "5001", [1001, 1002], [2001, 2002]).zero_ranges == ()
    # Only one of the two points selected: not own-site.
    assert site_info(own, "5001", [1001], [2001, 2002]).zero_ranges == ()


def test_unreadable_plan_skipped() -> None:
    """A changed plan shape drops the estimate, not the run."""

    raw = own_site_mp_raw()
    for mp in raw[0]["memberMeteringpoints"]:
        for plan in mp["sendingZeroPlans"] + mp["receivingZeroPlans"]:
            plan.pop("begin", None)
    info = parse_metering_points(raw)
    assert site_info(info, "5001", [1001, 1002], [2001]).zero_ranges == ()


